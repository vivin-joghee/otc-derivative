"""
Module 2: UPI Lookup Engine.

For each parsed trade, locate the matching ANNA-DSB product-definition template
and validate the trade's attribute values against the codesets the template
references. Two output statuses are used:

  FOUND                   - a template was located (exact or heuristic match);
                            validation errors / warnings, if any, are reported
                            in their respective lists. The classification_note
                            field carries an explanation when the match was
                            heuristic rather than exact.
  NO_PRODUCT_DEFINITION   - the trade was flagged NOVEL_INSTRUMENT_NO_TAXONOMY
                            in Module 1 (T026-T028 prediction contracts);
                            template lookup is bypassed.

UPI codes are returned as `null`: ANNA-DSB templates are JSON Schemas, not
records, and the UPI string for a specific product instance is generated by
DSB's live API at registration time. The cloned repo cannot supply it.
"""

from __future__ import annotations

